"""Build the DQX Studio application bundle (source-shipped, uv-run model).

Produces, under ``app/.build/`` — a self-contained source tree the
Databricks Apps runtime runs via ``uv run`` (no application wheel):

* ``pyproject.toml`` / ``uv.lock`` — the release form of the app's
  ``pyproject.toml``, pinned to the published DQX ``dqx_version`` from
  ``databricks.yml``, and the committed Marketplace lock resolved for it
  (``marketplace_templates/uv.lock``). DAB and Marketplace deploys therefore
  install the same published DQX and the same dependency versions, and
  ``uv run --frozen`` installs that lock inside the Apps container,
  regardless of the container's system Python.
* ``README.md`` — copied because ``[project].readme`` references it (hatch
  needs it when ``uv run`` installs the app package).
* ``src/databricks_labs_dqx_app/`` — the package source, including the built
  UI (``__dist__``), ``_metadata.py``, and ``_version.py``. The ``ui/``
  TypeScript source is excluded (only the compiled ``__dist__`` is needed at
  runtime).
* ``requirements.txt`` — the single line ``uv``. The Apps ``[BUILD]`` phase
  ``pip install``s this into the platform venv; ``uv`` then builds the real
  environment from ``pyproject.toml`` + ``uv.lock`` at launch — which is what
  lets the app target a newer Python than the container's system Python.
* ``app.yml`` — Databricks Apps launch manifest (``uv run uvicorn`` …), a
  fallback for non-DABs deploys; DABs overrides the command via
  ``var.app_config.command`` in ``databricks.yml``.

Side effects on the source tree:

* ``src/databricks_labs_dqx_app/_metadata.py`` and ``_version.py`` are
  regenerated (from ``[tool.dqx_app.metadata]`` and ``[project].version``).
* ``src/databricks_labs_dqx_app/ui/lib/api.ts`` is regenerated by orval.
* ``src/databricks_labs_dqx_app/__dist__/`` is overwritten by ``vite build``.

The script is invoked from the ``app-build`` Makefile target (and
transitively from the ``databricks.yml`` ``artifacts.default.build``
pipeline, which additionally builds the task-runner wheel for the job).
Designed to be cwd-independent — paths resolve relative to this file.
"""

import json
import os
import re
import shutil
import subprocess
import tempfile
import tomllib
from pathlib import Path

import yaml
from packaging.version import Version

APP_DIR = Path(__file__).resolve().parent.parent  # scripts/build_app.py → app/
PYPROJECT = APP_DIR / "pyproject.toml"
README = APP_DIR / "README.md"
BUILD_DIR = APP_DIR / ".build"
NODE_BIN = APP_DIR / "node_modules" / ".bin"

DQX_DIR = APP_DIR.parent
DAB_CONFIG = APP_DIR / "databricks.yml"
TEMPLATE_LOCK = APP_DIR / "marketplace_templates" / "uv.lock"
DQX_PACKAGE = "databricks-labs-dqx"
RELEASE_VERSION = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+(?:[A-Za-z0-9.-]*)")
# Mirrors ``[tool.hatch.build.targets.sdist].only-include`` in the DQX
# pyproject: the minimum hatchling needs to build the library from source.

PKG_DIR = APP_DIR / "src" / "databricks_labs_dqx_app"
METADATA_PY = PKG_DIR / "_metadata.py"
VERSION_PY = PKG_DIR / "_version.py"
API_TS = PKG_DIR / "ui" / "lib" / "api.ts"
DIST_DIR = PKG_DIR / "__dist__"
TASKS_DIR = APP_DIR / "tasks"
REPRODUCIBLE_BUILD_EPOCH = "315532800"


def _step(msg: str) -> None:
    print(f"\n▶ {msg}", flush=True)


def _run(
    cmd: list[str],
    *,
    cwd: Path = APP_DIR,
    env: dict[str, str] | None = None,
    quiet: bool = False,
) -> None:
    """Run a subprocess from ``APP_DIR`` with stdio passed through.

    Failures abort the build via ``check=True`` — every stage must
    succeed for the deploy tree to be considered usable.
    """
    if not quiet:
        print(f"  $ {' '.join(cmd)}", flush=True)
    output = subprocess.DEVNULL if quiet else None
    subprocess.run(cmd, cwd=cwd, check=True, env=env, stdout=output, stderr=output)  # noqa: S603


def _node_bin(name: str) -> str:
    """Return the path to a ``node_modules/.bin`` executable for this platform."""
    suffix = ".cmd" if os.name == "nt" else ""
    return str(NODE_BIN / f"{name}{suffix}")


def _load_pyproject() -> dict:
    with PYPROJECT.open("rb") as f:
        return tomllib.load(f)


def _read_app_metadata(pyproject: dict) -> dict[str, str]:
    """Return ``[tool.dqx_app.metadata]`` from ``pyproject.toml``.

    Single source of truth for app identity. ``vite.config.ts`` reads
    the same key — keeping the two consumers in lockstep on schema
    changes is intentional (rename here ⇒ rename there).
    """
    meta = pyproject.get("tool", {}).get("dqx_app", {}).get("metadata", {})
    required = {"app-name", "app-slug", "app-module"}
    missing = required - meta.keys()
    if missing:
        raise SystemExit(
            f"error: [tool.dqx_app.metadata] missing keys {sorted(missing)} in {PYPROJECT}",
        )
    return meta


def _write_metadata_module(meta: dict[str, str]) -> None:
    """Mirror ``[tool.dqx_app.metadata]`` into a runtime-importable module.

    ``backend.config`` and ``backend.logger`` import ``app_name`` /
    ``app_slug`` from here. Generating it on every build keeps
    source-of-truth in ``pyproject.toml`` while still letting runtime
    code do a plain ``from .._metadata import ...``.

    Uses ``json.dumps`` for value formatting because it always emits
    double-quoted strings, matching the existing file's convention and
    keeping the diff clean across repeat builds.
    """
    METADATA_PY.write_text(
        f"app_name = {json.dumps(meta['app-name'])}\n"
        f"app_module = {json.dumps(meta['app-module'])}\n"
        f"app_slug = {json.dumps(meta['app-slug'])}\n"
        'api_prefix = "/api"\n',
        encoding="utf-8",
    )


def _write_version_module(version: str) -> None:
    """Write the static ``_version.py`` imported by ``__init__``.

    Replaces the old git-based ``uv-dynamic-versioning`` build hook: the
    app ships as source with a static ``[project].version``, so the
    version is known without git (the Apps container has none).
    """
    VERSION_PY.write_text(f'version = "{version}"\n', encoding="utf-8")


def _write_app_yml(meta: dict[str, str]) -> None:
    """Write the Databricks Apps launch manifest (``uv run`` form).

    Single-worker uvicorn under ``uv run`` so the container resolves the
    locked environment (and required Python) at launch. Production DABs
    deploys override this via ``var.app_config.command`` in
    ``databricks.yml``; this manifest is the fallback for paths that don't
    go through DABs (e.g. direct ``databricks apps`` CLI deploys).
    """
    (BUILD_DIR / "app.yml").write_text(
        f'command: ["uv", "run", "--no-dev", "uvicorn", "{meta["app-module"]}", "--workers", "1"]\n',
        encoding="utf-8",
    )


def _dump_openapi() -> None:
    """Import the FastAPI app and serialize its OpenAPI schema.

    Runs in a subprocess via ``uv run`` so the schema is dumped with
    exactly the same environment the app uses — same pydantic / fastapi
    versions, same plugin set.
    """
    _run(openapi_dump_command(BUILD_DIR / "openapi.json"))


def openapi_dump_command(target: Path) -> list[str]:
    """Return the frozen command used to generate an OpenAPI document.

    Args:
        target: Destination path for the generated JSON document.

    Returns:
        The uv command and Python snippet used by the application build.
    """
    code = (
        "import json, sys;"
        "from databricks_labs_dqx_app.backend.app import app;"
        f"open({str(target)!r}, 'w').write(json.dumps(app.openapi(), indent=2))"
    )
    return ["uv", "run", "--frozen", "--exact", "--all-extras", "python", "-c", code]


def _run_orval() -> None:
    """Regenerate ``ui/lib/api.ts`` from ``.build/openapi.json``.

    Config picked up from ``orval.config.ts`` at app root. Invokes the
    locally-installed binary directly so the pinned ``orval`` is used
    regardless of which package manager is on PATH.
    """
    _run([_node_bin("orval")])


def _run_vite_build() -> None:
    """Compile the React UI into ``src/databricks_labs_dqx_app/__dist__/``.

    Vite reads ``vite.config.ts``, which sets ``build.outDir`` to the
    package's ``__dist__`` folder so it ships inside the package source.
    """
    _run([_node_bin("vite"), "build"])


def assemble_deploy_tree() -> None:
    """Assemble the source tree the Apps runtime runs via ``uv run``.

    Writes the release ``pyproject.toml`` (pinned to the published DQX) and the
    committed Marketplace lock, copies ``README.md`` and the package ``src/``
    (minus the ``ui/`` TS source and caches) into ``.build/``, and writes
    ``requirements.txt`` = ``uv``. ``.build/tasks``
    (the task-runner wheel, built by the ``databricks.yml`` pipeline after
    this script) is left untouched.
    """
    # Sweep stale wheels from the previous (wheel-based) layout so they
    # don't linger in the synced source tree.
    for stale in list(BUILD_DIR.glob("*.whl")):
        stale.unlink()
    shutil.rmtree(BUILD_DIR / "wheels", ignore_errors=True)
    # Deploys no longer vendor the checkout's DQX; drop a copy left by an older build.
    shutil.rmtree(BUILD_DIR / "_vendor", ignore_errors=True)

    dqx_version = dqx_release_version()
    lock_text = release_lock_text(dqx_version)
    (BUILD_DIR / "pyproject.toml").write_text(
        release_pyproject(PYPROJECT.read_text(encoding="utf-8"), dqx_version), encoding="utf-8", newline="\n"
    )
    (BUILD_DIR / "uv.lock").write_text(lock_text, encoding="utf-8", newline="\n")
    shutil.copy2(README, BUILD_DIR / "README.md")

    dest_pkg = BUILD_DIR / "src" / "databricks_labs_dqx_app"
    shutil.rmtree(BUILD_DIR / "src", ignore_errors=True)
    shutil.copytree(
        PKG_DIR,
        dest_pkg,
        ignore=shutil.ignore_patterns("ui", "__pycache__", "*.pyc"),
    )

    (BUILD_DIR / "requirements.txt").write_text("uv\n", encoding="utf-8")


def dqx_release_version(bundle_path: Path = DAB_CONFIG) -> str:
    """Return the published DQX version Studio deploys against.

    Args:
        bundle_path: Bundle configuration holding the *dqx_version* variable.

    Returns:
        The *dqx_version* default from *databricks.yml*.
    """
    bundle = yaml.safe_load(bundle_path.read_text(encoding="utf-8"))
    try:
        version = bundle["variables"]["dqx_version"]["default"]
    except (KeyError, TypeError) as error:
        raise RuntimeError("Bundle DQX version is missing") from error
    if not isinstance(version, str) or RELEASE_VERSION.fullmatch(version) is None:
        raise RuntimeError("Bundle DQX version is invalid")
    return version


def release_pyproject(source: str, dqx_version: str) -> str:
    """Return the app *pyproject.toml* pinned to the published DQX.

    Pins *databricks-labs-dqx* to *dqx_version* and drops the local path source,
    dependency groups and tool settings, so it matches the committed lock.

    Args:
        source: The app's *pyproject.toml* text.
        dqx_version: Published DQX version to pin.

    Returns:
        The release *pyproject.toml* text.
    """
    lines = normalize_newlines(source).splitlines()
    dependency_index = next(
        (index for index, line in enumerate(lines) if '"databricks-labs-dqx[llm,datacontract]' in line),
        None,
    )
    if dependency_index is None:
        raise RuntimeError("Application DQX dependency declaration changed")

    comment_start = dependency_index
    while comment_start > 0 and lines[comment_start - 1].lstrip().startswith("#"):
        comment_start -= 1
    lines[comment_start : dependency_index + 1] = [f'    "databricks-labs-dqx[llm,datacontract]=={dqx_version}",']
    text = "\n".join(lines) + "\n"
    text = remove_toml_table(text, "dependency-groups")
    text = remove_toml_table(text, "tool.uv.sources", remove_leading_comments=True)
    text = remove_toml_table(text, "tool.uv")
    for table in ("tool.pytest.ini_options", "tool.ruff.lint", "tool.ruff", "tool.basedpyright"):
        text = remove_toml_table(text, table, remove_leading_comments=True)
    return normalize_newlines(text)


def release_lock_text(dqx_version: str) -> str:
    """Return the committed Marketplace lock, after checking it resolves *dqx_version*.

    The lock is a tracked template, not regenerated at build time: the build resolves
    and downloads nothing, so it cannot drift with the package index or a *uv* version.
    The *options* tables are dropped because the release *pyproject.toml* has no
    *tool.uv* settings. To refresh the lock, see *DEPLOYMENT.md*.

    Args:
        dqx_version: Published DQX version the lock must resolve.

    Returns:
        The lock text to deploy.
    """
    if not TEMPLATE_LOCK.is_file():
        raise RuntimeError("Committed Marketplace lock is missing")
    lock_text = normalize_newlines(TEMPLATE_LOCK.read_text(encoding="utf-8"))
    require_lock_resolves_dqx(lock_text, dqx_version)
    lock_text = remove_toml_table(lock_text, "options.exclude-newer-package")
    return remove_toml_table(lock_text, "options")


def require_lock_resolves_dqx(lock_text: str, dqx_version: str) -> None:
    """Fail unless *lock_text* resolves exactly the published *dqx_version*.

    The app installs the lock while the task runner installs the *dqx_version* pin,
    so the two must agree.

    Args:
        lock_text: *uv.lock* text.
        dqx_version: Published DQX version the release pins.
    """
    locked = {
        Version(package["version"])
        for package in tomllib.loads(lock_text).get("package", [])
        if isinstance(package, dict) and package.get("name") == DQX_PACKAGE and "version" in package
    }
    if locked != {Version(dqx_version)}:
        raise RuntimeError("Marketplace lock does not resolve the release DQX version")


def remove_toml_table(source: str, table: str, *, remove_leading_comments: bool = False) -> str:
    """Remove the *table* section (header through the next header) from TOML *source*."""
    lines = source.splitlines()
    header = f"[{table}]"
    try:
        start = lines.index(header)
    except ValueError:
        return source
    end = next((index for index in range(start + 1, len(lines)) if lines[index].startswith("[")), len(lines))
    if remove_leading_comments:
        while start > 0 and lines[start - 1].lstrip().startswith("#"):
            start -= 1
    del lines[start:end]
    while start < len(lines) - 1 and lines[start] == "" and lines[start + 1] == "":
        del lines[start]
    return "\n".join(lines).rstrip() + "\n"


def normalize_newlines(value: str) -> str:
    """Return *value* with LF line endings."""
    return value.replace("\r\n", "\n").replace("\r", "\n")


def build_task_runner_wheel(output_dir: Path, dqx_version: str) -> Path:
    """Build a reproducible task-runner wheel pinned to the released DQX version.

    The regular bundle build keeps resolving the runner's DQX dependency through
    the bundle environment. Marketplace has no sibling checkout or bundle
    variable, so its wheel metadata must carry the same exact release pin as the
    application. The tracked task-runner project is never modified.

    Args:
        output_dir: Directory that will contain the single built wheel.
        dqx_version: Published DQX version required by the wheel.

    Returns:
        Path to the built task-runner wheel.
    """
    if re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+(?:[A-Za-z0-9.-]*)", dqx_version) is None:
        raise ValueError("dqx_version must be a release version")

    shutil.rmtree(output_dir, ignore_errors=True)
    output_dir.mkdir(parents=True)
    with tempfile.TemporaryDirectory(prefix=".marketplace-task-", dir=output_dir.parent) as temp_dir:
        task_source = Path(temp_dir) / "tasks"
        shutil.copytree(
            TASKS_DIR,
            task_source,
            ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "uv.lock"),
        )
        task_pyproject = task_source / "pyproject.toml"
        task_text = task_pyproject.read_text(encoding="utf-8")
        task_text, replacements = re.subn(
            r'(?m)^(\s*)"databricks-labs-dqx",$',
            rf'\1"databricks-labs-dqx=={dqx_version}",',
            task_text,
        )
        if replacements != 1:
            raise RuntimeError("Task-runner DQX dependency declaration changed")
        task_pyproject.write_text(task_text.replace("\r\n", "\n"), encoding="utf-8", newline="\n")

        build_env = os.environ.copy()
        build_env["SOURCE_DATE_EPOCH"] = REPRODUCIBLE_BUILD_EPOCH
        build_env["PYTHONHASHSEED"] = "0"
        build_env["UV_BUILD_CONSTRAINT"] = str(DQX_DIR / ".build-constraints.txt")
        for name in ("UV_INDEX", "UV_EXTRA_INDEX_URL", "PIP_INDEX_URL", "PIP_EXTRA_INDEX_URL"):
            build_env.pop(name, None)
        try:
            _run(
                ["uv", "build", ".", "--wheel", "--out-dir", str(output_dir)],
                cwd=task_source,
                env=build_env,
                quiet=True,
            )
        except subprocess.CalledProcessError as error:
            raise RuntimeError("Task-runner wheel build failed") from error

    wheels = sorted(output_dir.glob("databricks_labs_dqx_task_runner-*.whl"))
    if len(wheels) != 1:
        raise RuntimeError("Task-runner build did not produce exactly one wheel")
    (output_dir / ".gitignore").unlink(missing_ok=True)
    return wheels[0]


def main() -> int:
    BUILD_DIR.mkdir(parents=True, exist_ok=True)

    pyproject = _load_pyproject()
    meta = _read_app_metadata(pyproject)
    version = pyproject["project"]["version"]

    _step("Writing _metadata.py from pyproject [tool.dqx_app.metadata]")
    _write_metadata_module(meta)

    _step(f"Writing _version.py (version={version})")
    _write_version_module(version)

    _step("Writing .build/app.yml")
    _write_app_yml(meta)

    _step("Dumping FastAPI OpenAPI schema → .build/openapi.json")
    _dump_openapi()

    _step("Generating UI API client (orval)")
    _run_orval()

    _step("Building UI bundle (vite build → src/databricks_labs_dqx_app/__dist__/)")
    _run_vite_build()

    _step(f"Assembling .build/ source tree pinned to databricks-labs-dqx=={dqx_release_version()}")
    assemble_deploy_tree()

    _step("Build complete:")
    print(f"  → {(BUILD_DIR / 'src' / 'databricks_labs_dqx_app').relative_to(APP_DIR)} (source), requirements.txt=uv")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
